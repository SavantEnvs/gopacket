#!/usr/bin/env bash
#
# gopacket/mayhem/test.sh — RUN google/gopacket's OWN upstream test suite AND the
# mayhem/kat known-answer probe, and emit a CTRF summary. exit 0 iff nothing failed.
#
# The suite is the exact set upstream CI ran (.travis.script.sh):
#     go test .            (core packet/decode/flows)
#     go test ./layers     (every layer's known-answer decode/serialize tests)
#     go test ./tcpassembly
#     go test ./reassembly
#     go test ./pcapgo     (pcap/pcapng/snoop file read+write round-trips)
#     (./pcap — libpcap cgo bindings — does not build at this BASE; see PKGS below)
#     go test ./routing    — SKIPPED: upstream runs it under sudo (netlink route
#                            table access); not available to the unprivileged
#                            `mayhem` build identity.
# These are REAL known-answer suites: layer tests decode embedded packet bytes and
# assert every decoded field against golden structs (and re-serialize + compare
# bytes), so a no-op/exit(0) patch to the decoders FAILS them.
#
# Anti-reward-hacking (SPEC §6.3): `go test` links a STATIC binary, so the
# verify-repo LD_PRELOAD sabotage shim cannot neuter it — a `go test`-only oracle
# would survive sabotage while asserting nothing. mayhem/kat is a SEPARATE,
# dynamically linked probe (forced via cgo, see mayhem/kat/cgo_dynamic.go) that
# decodes a fixed packet fixture and prints exact field values; the shim DOES
# neuter it, so its output vanishes and the exact-match assertions below fail.
set -uo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
: "${MAYHEM_JOBS:=$(nproc)}"

export PATH="/opt/toolchains/go/bin:/opt/toolchains/go-path/bin:$PATH"
export GOFLAGS="${GOFLAGS:--mod=mod}"
export GOTOOLCHAIN="${GOTOOLCHAIN:-local}"
export GOMODCACHE="${GOMODCACHE:-/opt/toolchains/go-path/pkg/mod}"
export GOCACHE="${GOCACHE:-/opt/toolchains/go-path/build-cache}"
# Offline-first: resolve from the in-image module cache (filled by build.sh).
export GOPROXY="${GOPROXY:-file://$(go env GOMODCACHE 2>/dev/null || echo /opt/toolchains/go-path/pkg/mod)/cache/download,off}"
: "${SRC:=/mayhem}"
cd "$SRC"

# emit_ctrf <tool> <passed> <failed> [skipped] [pending] [other]
emit_ctrf() {
  local tool="$1" passed="$2" failed="$3" skipped="${4:-0}" pending="${5:-0}" other="${6:-0}"
  local tests=$(( passed + failed + skipped + pending + other ))
  cat > "${CTRF_REPORT:-$SRC/ctrf-report.json}" <<JSON
{
  "results": {
    "tool": { "name": "$tool" },
    "summary": {
      "tests": $tests,
      "passed": $passed,
      "failed": $failed,
      "pending": $pending,
      "skipped": $skipped,
      "other": $other
    }
  }
}
JSON
  printf 'CTRF {"results":{"tool":{"name":"%s"},"summary":{"tests":%d,"passed":%d,"failed":%d,"pending":%d,"skipped":%d,"other":%d}}}\n' \
    "$tool" "$tests" "$passed" "$failed" "$pending" "$skipped" "$other"
  [ "$failed" -eq 0 ]
}

PASSED=0; FAILED=0; SKIPPED=0

if ! command -v go >/dev/null 2>&1; then
  echo "go not available — cannot run the test suite" >&2
  emit_ctrf "go-test+kat" 0 1 0; exit 2
fi

# ./pcap is left out: at this 2018 BASE its cgo code no longer builds under the current Go
# ("identifier _Ctype_struct_bpf_program may conflict with identifiers generated by cgo").
PKGS=". ./layers ./tcpassembly ./reassembly ./pcapgo"

mkdir -p "$SRC/mayhem-build"
JSON="$SRC/mayhem-build/gotest.json"
echo "=== running: go test -count=1 -vet=off -json $PKGS ==="
go test -count=1 -vet=off -json $PKGS > "$JSON" 2>"$SRC/mayhem-build/gotest.err"; rc=$?

# Human-readable package summary + surface any build errors.
grep '"Action":"output"' "$JSON" 2>/dev/null | grep -E '"(ok  |FAIL|--- FAIL)' | head -30 || true
tail -5 "$JSON" | grep -o '"Package":"[^"]*","Action":"[a-z]*"' || true
[ -s "$SRC/mayhem-build/gotest.err" ] && { echo "--- stderr ---"; tail -20 "$SRC/mayhem-build/gotest.err"; }

# Count test-level events (lines carrying a non-empty "Test" field). Subtests count —
# each is a distinct asserted case. Package-level lines have no "Test" field.
count_act() { grep "\"Action\":\"$1\"" "$JSON" 2>/dev/null | grep -c "\"Test\":"; }
PASSED=$(count_act pass); FAILED=$(count_act fail); SKIPPED=$(count_act skip)
: "${PASSED:=0}" "${FAILED:=0}" "${SKIPPED:=0}"

if [ "$(( PASSED + FAILED + SKIPPED ))" -eq 0 ]; then
  echo "FAIL: no test events parsed; go exit code $rc" >&2
  emit_ctrf "go-test+kat" 0 1 0; exit 1
fi

# If go reported failure but we parsed 0 failed tests (e.g. a package build error),
# force a failure so the oracle stays honest.
if [ "$rc" -ne 0 ] && [ "$FAILED" -eq 0 ]; then FAILED=$(( FAILED + 1 )); fi

# ── KAT probe (sabotage-detecting; see header) ─────────────────────────────────
# UNCONDITIONAL by design: a missing binary is a FAILURE, never a skip. A
# `[ -x ... ]` guard here is how a probe silently stops running and the oracle
# quietly degrades to the go-test-only (reward-hackable, statically-linked) case.
echo "=== KAT probe: /mayhem/kat (dynamically linked; asserts decoded VALUES) ==="
KAT_OUT="$(/mayhem/kat 2>&1)"; kat_rc=$?
echo "$KAT_OUT"

# Expected values are upstream's OWN golden fixture (layers/decode_test.go
# TestDecode asserts these exact fields for testSimpleTCPPacket via reflect.DeepEqual):
#   Eth Src bc:30:5b:e8:d3:49   Eth Dst 00:00:0c:9f:f0:20
#   IP  Src 172.17.81.73        IP  Dst 173.222.254.225
#   TCP Src 50679               TCP Dst 80
#   Payload starts "GET / HTTP/1.1"
kat_expect() {
  local label="$1" line="$2"
  if printf '%s\n' "$KAT_OUT" | grep -qxF "$line"; then
    echo "KAT PASS: $label"
    PASSED=$(( PASSED + 1 ))
  else
    echo "KAT FAIL: $label — expected exact line: $line" >&2
    FAILED=$(( FAILED + 1 ))
  fi
}

if [ "$kat_rc" -ne 0 ]; then
  echo "KAT FAIL: /mayhem/kat exited $kat_rc (neutered, missing, or decoder broken)" >&2
  FAILED=$(( FAILED + 1 ))
fi
kat_expect "Ethernet source MAC"       'KAT_ETH_SRC=bc:30:5b:e8:d3:49'
kat_expect "Ethernet destination MAC" 'KAT_ETH_DST=00:00:0c:9f:f0:20'
kat_expect "IPv4 source address"       'KAT_IP_SRC=172.17.81.73'
kat_expect "IPv4 destination address"  'KAT_IP_DST=173.222.254.225'
kat_expect "TCP source port"           'KAT_TCP_SRC=50679'
kat_expect "TCP destination port"      'KAT_TCP_DST=80'
kat_expect "application payload prefix" 'KAT_PAYLOAD_PREFIX=GET / HTTP/1.1'

emit_ctrf "go-test+kat" "$PASSED" "$FAILED" "$SKIPPED"
